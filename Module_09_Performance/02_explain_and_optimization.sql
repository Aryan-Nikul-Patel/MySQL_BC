-- ────────────────────────────────────────────
-- 📌 CONCEPT 1: Deciphering EXPLAIN Output
-- ────────────────────────────────────────────
-- 💬 In SQL performance rounds, you will be asked to explain what happens when a query runs slow.
--    `EXPLAIN` shows the query execution plan generated by the optimizer.
--
--    Key EXPLAIN columns to know for interviews:
--    - **type**: Join type. Ranked from best to worst:
--      1. `system`/`const`: Single row lookup (Primary Key or Unique index).
--      2. `eq_ref`: 1-to-1 join matching primary key.
--      3. `ref`: 1-to-many lookup using non-unique index.
--      4. `range`: Index range scan (using <, >, BETWEEN, IN on index).
--      5. `index`: Full index scan (scans the index tree only — covering index).
--      6. `ALL`: Full table scan (scans all data blocks — worst!).
--    - **key**: The actual index chosen.
--    - **rows**: Estimate of the number of rows the engine needs to inspect.
--    - **Extra**: Additional details (e.g. "Using filesort" = slow sorting, "Using temporary" = slow group by/union).
--
--    🔥 MySQL 8.0+ features `EXPLAIN ANALYZE`, which actually RUNS the query and returns
--    exact execution times and cost estimations.

-- ▶ Example 1.1: Running EXPLAIN ANALYZE
--    This outputs a tree layout showing the physical operators, execution cost, and actual time (in ms).
EXPLAIN ANALYZE SELECT * FROM large_orders WHERE region = 'North';


-- ────────────────────────────────────────────
-- 📌 CONCEPT 2: SARGable vs Non-SARGable Queries
-- ────────────────────────────────────────────
-- 🔥 Critical Interview Concept: **SARGable** (Search Argument Able) Queries.
--    A query is SARGable if the database engine can directly utilize an index to find rows.
--    If you wrap an indexed column in a function, the engine must evaluate that function for EVERY single row,
--    disabling index lookups and forcing a Full Table Scan!
--
--    Non-SARGable: `WHERE YEAR(order_date) = 2025`
--    SARGable:     `WHERE order_date >= '2025-01-01' AND order_date < '2026-01-01'`
--
--    Let's check the execution plans for both.

-- First, create an index on order_date
CREATE INDEX idx_order_date ON large_orders (order_date);

-- ▶ Example 2.1: Non-SARGable query (Function on Column)
--    Notice: key is NULL, type is ALL. The index is bypassed!
EXPLAIN SELECT * FROM large_orders 
WHERE YEAR(order_date) = 2025;

-- ▶ Example 2.2: SARGable version of the same query
--    Notice: key is idx_order_date, type is range. The index is successfully used!
EXPLAIN SELECT * FROM large_orders 
WHERE order_date >= '2025-01-01' AND order_date < '2026-01-01';


-- ────────────────────────────────────────────
-- 📌 CONCEPT 3: Common Optimization Best Practices
-- ────────────────────────────────────────────
-- 💬 When an interviewer asks "How would you optimize this slow query?", present these checkpoints:
--
--    1. **Avoid SELECT *:** Retrieve only the specific columns you need. It reduces network payload,
--       I/O overhead, and allows Covering Indexes.
--    2. **Avoid Wildcard Prefixes:** `LIKE '%search'` is non-sargable because B-trees are sorted left-to-right.
--       Use `LIKE 'search%'` (which is sargable) or Full-Text search.
--    3. **Avoid OR conditions across different columns:**
--       `WHERE customer_id = 5 OR product_id = 10` often forces a full scan.
--       Rewrite using `UNION` to combine results of two indexed queries.
